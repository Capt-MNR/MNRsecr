import type { BrainRiskLevel, BrainStrategyLevel } from "../../src/lib/brain-contract";

export type EvaluationStatus =
  | "PASS"
  | "FAIL"
  | "BLOCKED_BY_INFRASTRUCTURE"
  | "NOT_EXECUTABLE";

export type ScenarioExecutionMode = "envelope" | "blocked" | "not_executable";

export type ContractExpectation = {
  primaryIntent: string;
  secondaryIntents: string[];
  mentionedEntities: string[];
  resolvedEntities: string[];
  ambiguousEntities: string[];
  timeScope: string | null;
  knownInformation: string[];
  unknownInformation: string[];
  requiredContext: string[];
  optionalContext: string[];
  authoritativeSources: string[];
  excludedSources: string[];
  selectedStrategy: string;
  intelligenceLevels: BrainStrategyLevel[];
  confidence: "high" | "medium" | "low";
  risk: BrainRiskLevel;
  decision: string;
  action: string;
  approvalRequired: boolean | "policy";
  verificationPlan: string;
  expectedOutcome: string;
  forbidden: string[];
};

export type ContractScenario = {
  scenarioId: string;
  title: string;
  input: string;
  previousState?: string;
  context: string;
  executionMode: ScenarioExecutionMode;
  limitation?: string;
  expectation: ContractExpectation;
};

const expenseSources = ["structured_records", "entity_graph"];
const noMemoryFinancial = ["second_brain_financial_truth", "unverified_model_claims"];
const noMutation = "no mutation";

function scenario(
  scenarioId: string,
  title: string,
  input: string,
  expectation: Partial<ContractExpectation> & Pick<ContractExpectation, "primaryIntent" | "decision" | "action" | "expectedOutcome">,
  options: Pick<ContractScenario, "context" | "executionMode" | "limitation"> = {
    context: "none",
    executionMode: "envelope",
  },
): ContractScenario {
  return {
    scenarioId,
    title,
    input,
    ...options,
    expectation: {
      secondaryIntents: [],
      mentionedEntities: [],
      resolvedEntities: [],
      ambiguousEntities: [],
      timeScope: null,
      knownInformation: [],
      unknownInformation: [],
      requiredContext: [],
      optionalContext: [],
      authoritativeSources: [],
      excludedSources: [],
      selectedStrategy: "unspecified",
      intelligenceLevels: ["L0", "L1", "L2", "L3"],
      confidence: "medium",
      risk: "low",
      approvalRequired: false,
      verificationPlan: "not applicable",
      forbidden: [],
      ...expectation,
    },
  };
}

